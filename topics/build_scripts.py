def dump(script: dict) -> None:
    path = OUT / f"{script['id']}.json"
    path.write_text(json.dumps(script, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    chars = sum(len(section["narration"]) for section in script["sections"])
    print(f"{script['id']}\tsections={len(script['sections'])}\tchars={chars}\tminutes={chars / 15.03 / 60:.2f}")


def section(group, heading, layout, lines, narration):
    return {
        "group": group,
        "heading": heading,
        "layout": layout,
        "lines": lines,
        "narration": " ".join(narration.split()),
    }


